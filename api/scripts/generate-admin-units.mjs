#!/usr/bin/env node
/**
 * Regenerates src/data/rwanda-admin-units.ts from the upstream dataset
 * https://github.com/japhetmoise/Rwanda_Administrative_Boundaries (data.json).
 *
 *   node scripts/generate-admin-units.mjs path/to/data.json
 *
 * Output is a compact nested-tuple TS module (not JSON) so it compiles into
 * dist/ with plain `tsc` and imports without JSON import attributes.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const input = process.argv[2]
if (!input) {
  console.error('usage: node scripts/generate-admin-units.mjs <data.json>')
  process.exit(1)
}

// Province names as the API has always stored them (see DISTRICT_TO_PROVINCE).
const PROVINCE_NAMES = {
  Kigali: 'Kigali City',
  East: 'Eastern Province',
  North: 'Northern Province',
  South: 'Southern Province',
  West: 'Western Province',
}

// Upstream spellings that differ from the official NISR sector names.
const SECTOR_FIXES = {
  'Rwamagana/Gishali': 'Gishari',
  'Nyarugenge/Mageregere': 'Mageragere',
}

const byName = (a, b) => a[0].localeCompare(b[0])
const clean = (s) => String(s).trim().replace(/\s+/g, ' ')

const raw = JSON.parse(fs.readFileSync(input, 'utf8'))
const counts = { provinces: 0, districts: 0, sectors: 0, cells: 0, villages: 0 }

const tree = raw.items.map((p) => {
  const province = PROVINCE_NAMES[clean(p.name)]
  if (!province) throw new Error(`Unknown province "${p.name}"`)
  counts.provinces++
  const districts = p.districts.map((d) => {
    counts.districts++
    const district = clean(d.name)
    const sectors = d.sectors.map((s) => {
      counts.sectors++
      const name = clean(s.name)
      const sector = SECTOR_FIXES[`${district}/${name}`] ?? name
      const cells = s.cells.map((c) => {
        counts.cells++
        const villages = [...new Set(c.villages.map(clean))].sort((a, b) => a.localeCompare(b))
        counts.villages += villages.length
        return [clean(c.name), villages]
      })
      return [sector, cells.sort(byName)]
    })
    return [district, sectors.sort(byName)]
  })
  return [province, districts.sort(byName)]
}).sort(byName)

const lines = [
  '// GENERATED by scripts/generate-admin-units.mjs. Do not edit by hand.',
  '// Source: https://github.com/japhetmoise/Rwanda_Administrative_Boundaries',
  `// ${counts.provinces} provinces, ${counts.districts} districts, ${counts.sectors} sectors, ${counts.cells} cells, ${counts.villages} villages`,
  '/* eslint-disable */',
  '',
  '/** [name, villages] */',
  'export type CellTuple = readonly [string, readonly string[]]',
  '/** [name, cells] */',
  'export type SectorTuple = readonly [string, readonly CellTuple[]]',
  '/** [name, sectors] */',
  'export type DistrictTuple = readonly [string, readonly SectorTuple[]]',
  '/** [name, districts] */',
  'export type ProvinceTuple = readonly [string, readonly DistrictTuple[]]',
  '',
  'export const RWANDA_ADMIN_UNITS: readonly ProvinceTuple[] = [',
]
for (const [province, districts] of tree) {
  lines.push(`  [${JSON.stringify(province)}, [`)
  for (const [district, sectors] of districts) {
    lines.push(`    [${JSON.stringify(district)}, [`)
    for (const [sector, cells] of sectors) {
      lines.push(`      [${JSON.stringify(sector)}, ${JSON.stringify(cells)}],`)
    }
    lines.push('    ]],')
  }
  lines.push('  ]],')
}
lines.push(']', '')

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, '..', 'src', 'data', 'rwanda-admin-units.ts')
fs.writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}`, counts)
